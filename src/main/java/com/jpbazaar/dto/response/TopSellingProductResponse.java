package com.jpbazaar.dto.response;

import io.swagger.v3.oas.annotations.media.Schema;

import java.math.BigDecimal;

@Schema(description = "Aggregated performance metrics for a top-selling product")
public record TopSellingProductResponse(
        @Schema(description = "Product unique identifier", example = "42")
        Long productId,

        @Schema(description = "Product display name", example = "Ultra HD 4K Smart TV")
        String productName,

        @Schema(description = "Product Stock Keeping Unit (SKU)", example = "ELEC-TV-4K-001")
        String sku,

        @Schema(description = "Total units sold across all non-cancelled orders", example = "145")
        long totalUnitsSold,

        @Schema(description = "Total gross revenue generated by this product", example = "724855.00")
        BigDecimal totalRevenue
) {
}
