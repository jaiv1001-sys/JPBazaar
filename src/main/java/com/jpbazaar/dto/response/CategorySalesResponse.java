package com.jpbazaar.dto.response;

import io.swagger.v3.oas.annotations.media.Schema;

import java.math.BigDecimal;

@Schema(description = "Aggregated sales and inventory breakdown by category")
public record CategorySalesResponse(
        @Schema(description = "Category unique identifier", example = "3")
        Long categoryId,

        @Schema(description = "Category name", example = "Electronics")
        String categoryName,

        @Schema(description = "Total number of products in this category", example = "48")
        long totalProducts,

        @Schema(description = "Total units sold across this category", example = "420")
        long unitsSold,

        @Schema(description = "Total revenue generated by products in this category", example = "1245000.00")
        BigDecimal totalRevenue
) {
}
